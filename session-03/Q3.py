#بین اعداد 1 تا 10 حرکت کنید:
#اگر عدد فرد بود، در ۵ ضرب شود.
#اگر عدد زوج بود، ۵ واحد به آن اضافه شود.
#در انتها مجموع کل را نمایش دهید.
total = 0

for number in range (1,11):
    if number % 2 == 0:
        #شرط زوج بودن
        total = total + number +5
    #مجموع جدید با قبلی جمع میشود و ریخته میشه درون توتال جدید
    else:
        total = total + number *5
        
print('مجموع اعداد مساوی است با :',total)