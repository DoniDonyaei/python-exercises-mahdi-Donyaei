#یک رشته دریافت کنید.
#اگر طول رشته زوج بود، نیمه اول را چاپ کنید.
#اگر فرد بود، نیمه دوم را چاپ کنید.

text = input(' لطفا رشته ی خود را وارد کنید : ')
if len(text) %2 == 0:
    #شرط زوج بودن
    print(text[:len(text)//2])  #نیمه ی اول رشته چاپ میشه
    
else:
    print(text[len(text)//2:]) # نیمه دوم رشته از اخر به اول چاپ میشه